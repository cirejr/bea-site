export const domainSlugs = Object.keys(domainConfig)

export function getCoursesByDomain(domain: string): CourseEntry[] {
  return courses.filter((c) => c.domain === domain)
}

export function getSubCategoriesByDomain(domain: string): { slug: string; label: string }[] {
  const seen = new Set<string>()
  return courses
    .filter((c) => c.domain === domain)
    .filter((c) => {
      if (seen.has(c.subCategory)) return false
      seen.add(c.subCategory)
      return true
    })
    .map((c) => ({ slug: c.subCategory, label: c.subCategoryLabel }))
}

export type ActiveFilters = {
  domain: string | null
  subCategory: string | null
  modalite: Modalite | null
  searchQuery?: string
}

export function filterCourses(filters: ActiveFilters): CourseEntry[] {
  return courses.filter((c) => {
    if (filters.domain && c.domain !== filters.domain) return false
    if (filters.subCategory && c.subCategory !== filters.subCategory) return false
    if (filters.modalite && !c.modalities.includes(filters.modalite)) return false
    if (filters.searchQuery) {
      const q = filters.searchQuery.toLowerCase()
      if (!c.title.toLowerCase().includes(q)) return false
    }
    return true
  })
}
